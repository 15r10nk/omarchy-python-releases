function resolveLanguage(localeName) {
  var code = String(localeName || "").toLowerCase().split(/[_\-.@]/)[0]
  return Object.prototype.hasOwnProperty.call(messages, code) ? code : "en"
}

function text(language, key, args) {
  var catalog = messages[language] || messages.en
  var value = catalog[key] || messages.en[key] || key
  return value.replace(/\{(\w+)\}/g, function(match, name) {
    return args && args[name] !== undefined ? String(args[name]) : match
  })
}

